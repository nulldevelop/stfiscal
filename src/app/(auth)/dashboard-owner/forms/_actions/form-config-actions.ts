'use server'

import { revalidatePath } from 'next/cache'
import { withPermission } from '@/lib/permissions/with-permission'
import { prisma } from '@/lib/prisma'

export const getFormConfigs = withPermission(
	'read',
	async (ctx, reportType: string) => {
		const configs = await prisma.formConfig.findMany({
			where: {
				reportType,
				organizationId: ctx.organizationId,
			},
			orderBy: { order: 'asc' },
		})
		return { success: true, data: configs }
	},
	'FORMS',
)

export const updateFormConfig = withPermission(
	'update',
	async (ctx, id: string, data: any) => {
		const updated = await prisma.formConfig.update({
			where: { id, organizationId: ctx.organizationId },
			data: {
				label: data.label,
				description: data.description,
				isActive: data.isActive,
				isRequired: data.isRequired,
				isVisiblePrincipal: data.isVisiblePrincipal,
				isVisibleSetorial: data.isVisibleSetorial,
				order: Number(data.order),
				hasObs: data.hasObs,
				requiredObsValue: data.requiredObsValue,
				options:
					typeof data.options === 'string'
						? data.options
						: JSON.stringify(data.options),
			},
		})

		ctx.log({
			entityId: id,
			entityName: data.label,
			description: `Atualizou configuração do campo: ${data.label} no relatório ${data.reportType}`,
			after: data,
		})

		revalidatePath('/dashboard-owner/forms')
		return { success: true, data: updated }
	},
	{ module: 'FORMS', log: 'FORM_CONFIG' },
)

export const createFormField = withPermission(
	'create',
	async (ctx, reportType: string, data: any) => {
		const created = await prisma.formConfig.create({
			data: {
				reportType,
				organizationId: ctx.organizationId,
				fieldKey: `custom_${Date.now()}`,
				label: data.label,
				type: data.type,
				section: data.section || 'Campos Adicionais',
				options: data.options ? JSON.stringify(data.options) : null,
				isVisiblePrincipal: true,
				isVisibleSetorial: true,
				isActive: true,
				hasObs: data.hasObs || false,
				requiredObsValue: data.requiredObsValue || null,
				order: 99,
			},
		})

		ctx.log({
			entityId: created.id,
			entityName: data.label,
			description: `Criou novo campo personalizado: ${data.label} para o relatório ${reportType}`,
			after: data,
		})

		revalidatePath('/dashboard-owner/forms')
		return { success: true, data: created }
	},
	{ module: 'FORMS', log: 'FORM_CONFIG' },
)

