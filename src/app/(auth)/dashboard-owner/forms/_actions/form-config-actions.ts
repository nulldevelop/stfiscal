export const seedDefaultFormConfigs = withPermission(
	'create',
	async (ctx, reportType: string) => {
		let defaultFields: any[] = []

		switch (reportType) {
			case 'BENS_SERVICOS':
				defaultFields = [...BENS_SERVICOS_DEFAULTS]
				break
			case 'TRANSPORTE':
				defaultFields = [...TRANSPORTE_DEFAULTS]
				break
			case 'OBRAS':
				defaultFields = [...OBRAS_DEFAULTS]
				break
			case 'FISCAL_PRINCIPAL':
				defaultFields = [...FISCAL_PRINCIPAL_DEFAULTS]
				break
			case 'TERCEIRIZACAO':
				defaultFields = [...TERCEIRIZACAO_DEFAULTS]
				break
			default:
				return {
					success: false,
					error: 'Tipo de relatório não suportado para inicialização.',
				}
		}

		const defaults = defaultFields.map((d) => ({
			...d,
			reportType,
			organizationId: ctx.organizationId,
		}))

		const result = await prisma.formConfig.createMany({
			data: defaults,
			skipDuplicates: true,
		})

		revalidatePath('/dashboard-owner/forms')
		return { success: true, data: { created: result.count } }
	},
	{ module: 'FORMS', log: 'FORM_CONFIG' },
)

export const deleteFormField = withPermission(
	'delete',
	async (ctx, id: string) => {
		const config = await prisma.formConfig.findUnique({
			where: { id, organizationId: ctx.organizationId },
		})

		if (!config) {
			return { success: false, error: 'Campo não encontrado' }
		}

		await prisma.formConfig.delete({
			where: { id },
		})

		ctx.log({
			entityId: id,
			entityName: config.label,
			description: `Removeu o campo: ${config.label} do relatório ${config.reportType}`,
			before: config,
		})

		revalidatePath('/dashboard-owner/forms')
		return { success: true, data: null }
	},
	{ module: 'FORMS', log: 'FORM_CONFIG' },
)
